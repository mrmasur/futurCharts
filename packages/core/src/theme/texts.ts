/**
 * Texts the marks and the chart write for the reader (tooltip rows, headers, captions, counters, the summary and table read by screen readers, the play bar), as `theme.texts`.
 * French by default; `englishTexts` is a ready-made English set:
 *   theme: { texts: englishTexts }            every text
 *   theme: { texts: { median: 'Median' } }    one text, the others stay
 * A text with a `{name}` takes a value at drawing time (`fillText`). Dates and numbers follow the
 * browser's language (Intl) and are not here.
 */
import type { Theme } from './theme';

export type ThemeTexts = Theme['texts'];

/** Replace each `{name}` of `template` by `values[name]`; unknown names are left as they are. */
export function fillText(template: string, values: Record<string, string | number>): string {
  // One pass: a value that itself contains `{x}` is not expanded again.
  return template.replace(/\{(\w+)\}/g, (all, name: string) => (Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : all));
}

/** The `{name}` placeholders of a template, sorted (to compare two languages). */
export function textVariables(template: string): string[] {
  return [...new Set([...template.matchAll(/\{(\w+)\}/g)].map((m) => m[1]))].sort();
}

